import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const source = (file: string) => readFileSync(file, 'utf8')
const packageController = source('src/render-next/packages/PackageController.ts')
const transport = source('src/render-next/packages/transport.ts')
const serviceFiles = source('src/render-next/state/serviceFilesController.ts')
const databaseTools = source('src/render-next/state/databaseToolsController.ts')
const databasePanel = source('src/render-next/components/DatabaseToolsPanel.vue')
const capabilities = source('src/render-next/packages/capabilities.ts')
for (const marker of ['private mutation?', 'PackageOutcomeUnknown', 'this.deps.installed', 'this.deps.changed']) assert.ok(packageController.includes(marker), marker)
for (const marker of ['PackageOutcomeUnknown', 'options.mutation', 'ipc.off']) assert.ok(transport.includes(marker), marker)
for (const marker of ['listConfigFiles', 'listLogFiles', 'readFileStrict', 'The file changed outside', 'clearLog']) assert.ok(serviceFiles.includes(marker), marker)
for (const marker of ['MySQLManage', 'passwordChange', 'dataDirectory', 'revealDataDirectory']) assert.ok(databaseTools.includes(marker), marker)
assert.ok(databasePanel.includes('Change root password'))
assert.ok(capabilities.includes('PackageUpdateMode'))
assert.ok(capabilities.includes('legacy-upgrade'))
console.log('PQT Forge Phase 2 smoke passed (package lifecycle, service files, database access and failure boundaries).')
